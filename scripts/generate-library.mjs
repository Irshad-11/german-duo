// Parses data/library-tree.txt (authoritative inventory) and data/curriculum.mjs
// and writes: src/data/library.json, src/data/curriculum.json,
//             supabase/migrations/0002_seed_library.sql, supabase/migrations/0003_seed_curriculum.sql
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { parseTree, resolveRef, buildCategory, titleOf } from './lib-inventory.mjs';
import { weeks } from '../data/curriculum.mjs';

const tree = readFileSync(new URL('../data/library-tree.txt', import.meta.url), 'utf8');
const library = parseTree(tree);
const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'null' : String(v));

const items = [];
for (const w of weeks) {
  w.items.forEach((it, i) => {
    const r = resolveRef(library, it.ref);
    let start = null, end = null;
    if (it.pages === 'all') {
      if (!r.page_count) throw new Error(`'all' pages but no page count: ${it.ref}`);
      start = 1; end = r.page_count;
    } else if (Array.isArray(it.pages)) { [start, end] = it.pages; }
    items.push({
      week_no: w.week, position: i, resource_path: r.library_path, role: it.role,
      start_page: start, end_page: end, est_minutes: it.minutes, note: it.note ?? null,
      needs_page_selection: it.pages === null && (r.page_count ?? 0) > 12,
    });
  });
}
const weekRows = weeks.map((w) => ({ week_no: w.week, level: w.level, theme: w.theme, goal: w.goal }));

mkdirSync(new URL('../src/data/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/data/library.json', import.meta.url), JSON.stringify(library, null, 1));
writeFileSync(new URL('../src/data/curriculum.json', import.meta.url), JSON.stringify({ weeks: weekRows, items }, null, 1));

let sql = `-- GENERATED by scripts/generate-library.mjs from data/library-tree.txt. Do not edit by hand.\n`;
sql += `-- Seed data: the learner-supplied resource inventory (metadata only, no file contents).\n`;
sql += `insert into public.resources (library_path, level, category, source_folder, filename, file_type, page_count, size_kb, title, is_catalog) values\n`;
sql += library.map((r) => `(${q(r.library_path)}, ${q(r.level)}, ${q(buildCategory(r))}, ${q(r.source_folder)}, ${q(r.filename)}, ${q(r.file_type)}, ${n(r.page_count)}, ${n(r.size_kb)}, ${q(titleOf(r))}, true)`).join(',\n');
sql += `\non conflict (library_path) do nothing;\n`;
writeFileSync(new URL('../supabase/migrations/0002_seed_library.sql', import.meta.url), sql);

let c = `-- GENERATED by scripts/generate-library.mjs from data/curriculum.mjs. Do not edit by hand.\n`;
c += `-- Initial curriculum proposal: sequencing is inferred from filenames and metadata only. Editable in the app.\n`;
c += `insert into public.curriculum_weeks (week_no, level, theme, goal) values\n`;
c += weekRows.map((w) => `(${w.week_no}, ${q(w.level)}, ${q(w.theme)}, ${q(w.goal)})`).join(',\n');
c += `\non conflict (week_no) do nothing;\n\n`;
c += `insert into public.curriculum_items (week_no, position, resource_path, role, start_page, end_page, est_minutes, note, needs_page_selection) values\n`;
c += items.map((i) => `(${i.week_no}, ${i.position}, ${q(i.resource_path)}, ${q(i.role)}, ${n(i.start_page)}, ${n(i.end_page)}, ${i.est_minutes}, ${q(i.note)}, ${i.needs_page_selection})`).join(',\n');
c += `\non conflict (week_no, position) do nothing;\n`;
writeFileSync(new URL('../supabase/migrations/0003_seed_curriculum.sql', import.meta.url), c);
console.log(`library: ${library.length} files, curriculum: ${weekRows.length} weeks, ${items.length} items`);
